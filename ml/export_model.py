"""Export a trained int8 .tflite model into firmware/src/tinyml/model_data.{h,cpp}.

The generated files carry everything the firmware needs to guarantee that
embedded inference sees exactly what training saw:
  * the flatbuffer (in flash, 16-byte aligned)
  * feature standardisation (mean / std, in firmware feature order)
  * the FNV-1a hash of the feature specification string -> Classifier_Init()
    refuses a model trained on a different feature list/order
  * reference vectors: inputs + the Python TFLite interpreter's int8 output,
    which the host unit test compares bit-exactly with TFLM.

Usage (normally called by train_model.py):
    python ml/export_model.py --tflite build/pq_model.tflite --meta build/pq_model_meta.json
"""
from __future__ import annotations

import argparse
import datetime as _dt
import json
import pathlib

import numpy as np

REPO = pathlib.Path(__file__).resolve().parents[1]
DEFAULT_OUT = REPO / "firmware" / "src" / "tinyml"
CLASS_NAMES = ["NORMAL", "SAG", "SWELL", "INTERRUPTION", "HARMONIC", "TRANSIENT",
               "FREQUENCY_VARIATION", "LOAD_SWITCHING"]


def fnv1a32(s: str) -> int:
    h = 2166136261
    for b in s.encode():
        h ^= b
        h = (h * 16777619) & 0xFFFFFFFF
    return h


def _floats(vals, per_line=6) -> str:
    items = [f"{float(v):.9e}f" for v in vals]   # always a valid float literal
    lines = [", ".join(items[i:i + per_line]) for i in range(0, len(items), per_line)]
    return ",\n    ".join(lines)


def tflite_int8_probs(model_bytes: bytes, x_std: np.ndarray) -> np.ndarray:
    """Run the int8 model exactly like the firmware: quantise standardized input,
    invoke, dequantise the int8 softmax output."""
    import tensorflow as tf
    interp = tf.lite.Interpreter(model_content=model_bytes)
    interp.allocate_tensors()
    inp = interp.get_input_details()[0]
    out = interp.get_output_details()[0]
    s_in, zp_in = inp["quantization"]
    s_out, zp_out = out["quantization"]
    res = np.zeros((len(x_std), out["shape"][1]), dtype=np.float64)
    for i, x in enumerate(x_std):
        q = np.clip(np.round(x / s_in) + zp_in, -128, 127).astype(np.int8)[None, :]
        interp.set_tensor(inp["index"], q)
        interp.invoke()
        o = interp.get_tensor(out["index"])[0].astype(np.int32)
        res[i] = (o - zp_out) * s_out
    return res


def export(tflite_path: pathlib.Path, meta: dict, ref_x: np.ndarray, out_dir: pathlib.Path = DEFAULT_OUT) -> None:
    model = tflite_path.read_bytes()
    features = meta["features"]
    spec = ",".join(features)
    spec_hash = fnv1a32(spec)
    if "spec_hash" in meta and int(meta["spec_hash"], 16) != spec_hash:
        raise SystemExit(f"feature spec hash mismatch: dataset {meta['spec_hash']} vs {spec_hash:#010x}")
    mean = np.asarray(meta["mean"], dtype=np.float64)
    std = np.asarray(meta["std"], dtype=np.float64)
    nf, nc = len(features), len(CLASS_NAMES)

    # Reference vectors (raw feature values, as the firmware produces them).
    ref_x = np.asarray(ref_x, dtype=np.float32)
    ref_probs = tflite_int8_probs(model, ((ref_x - mean) / std).astype(np.float32))
    ref_cls = ref_probs.argmax(axis=1)

    version = meta.get("version") or _dt.datetime.utcnow().strftime("pq-mlp-%Y%m%d-%H%M")
    hdr = f"""// AUTO-GENERATED by ml/export_model.py — do not edit by hand.
// Model: {version}   size: {len(model)} bytes   test accuracy (int8): {meta.get('test_accuracy', 0):.4f}
// Feature spec ({nf}): {spec}
#pragma once
#include <cstdint>

namespace pq::model {{

extern const unsigned char kModel[];
extern const unsigned int kModelLen;
constexpr int kNumFeatures = {nf};
constexpr int kNumClasses = {nc};
constexpr unsigned kFeatureSpecHash = 0x{spec_hash:08X}u;
extern const float kFeatureMean[kNumFeatures];
extern const float kFeatureStd[kNumFeatures];
extern const char* const kClassNames[kNumClasses];
constexpr const char* kModelVersion = "{version}";
constexpr float kTestAccuracy = {float(meta.get('test_accuracy', 0)):.6f}f;

// Reference vectors: raw features and the int8 TFLite output computed in Python.
constexpr int kNumRefVectors = {len(ref_x)};
extern const float kRefInput[kNumRefVectors][kNumFeatures];
extern const int kRefClass[kNumRefVectors];
extern const float kRefProbs[kNumRefVectors][kNumClasses];

}}  // namespace pq::model
"""
    nl = "\n    "
    body = ",".join((nl if i % 16 == 0 else " ") + f"0x{b:02x}" for i, b in enumerate(model))
    cpp = f"""// AUTO-GENERATED by ml/export_model.py — do not edit by hand.
#include "tinyml/model_data.h"

namespace pq::model {{

alignas(16) const unsigned char kModel[] = {{{body}
}};
const unsigned int kModelLen = {len(model)};

const float kFeatureMean[kNumFeatures] = {{
    {_floats(mean)}}};
const float kFeatureStd[kNumFeatures] = {{
    {_floats(std)}}};
const char* const kClassNames[kNumClasses] = {{{", ".join(f'"{c}"' for c in CLASS_NAMES)}}};

const float kRefInput[kNumRefVectors][kNumFeatures] = {{
{chr(10).join("    {" + _floats(r, 7) + "}," for r in ref_x)}
}};
const int kRefClass[kNumRefVectors] = {{{", ".join(str(int(c)) for c in ref_cls)}}};
const float kRefProbs[kNumRefVectors][kNumClasses] = {{
{chr(10).join("    {" + _floats(p, 8) + "}," for p in ref_probs)}
}};

}}  // namespace pq::model
"""
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "model_data.h").write_text(hdr)
    (out_dir / "model_data.cpp").write_text(cpp)
    print(f"wrote {out_dir / 'model_data.h'} and model_data.cpp ({len(model)} B model, spec hash {spec_hash:#010x})")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--tflite", required=True, type=pathlib.Path)
    ap.add_argument("--meta", required=True, type=pathlib.Path)
    ap.add_argument("--out", type=pathlib.Path, default=DEFAULT_OUT)
    a = ap.parse_args()
    meta = json.loads(a.meta.read_text())
    export(a.tflite, meta, np.asarray(meta["ref_inputs"], dtype=np.float32), a.out)


if __name__ == "__main__":
    main()
